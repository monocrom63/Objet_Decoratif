export type Language = "DE" | "EN";

export function translate(text: string, language: Language): string {
  if (language === "EN") return text;
  const key = text.trim().replace(/\s+/g, " ");
  let translated = german[key];
  // Refill variants remain canonical in cart/order data; translate only their display.
  if (!translated && /^(Small|Big) \/ /.test(key)) {
    const [size, ...rest] = key.split(" / ");
    translated = `${german[size]} / ${rest.join(" / ")}`;
  }
  if (!translated) return text; // User-authored CMS content and proper names are not machine-translated.
  return `${text.match(/^\s*/)?.[0] ?? ""}${translated}${text.match(/\s*$/)?.[0] ?? ""}`;
}
